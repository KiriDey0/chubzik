import AppKit
import ApplicationServices
import SwiftUI
import UniformTypeIdentifiers

struct PocketEntry: Codable, Identifiable {
    let id: UUID
    let copied: Date
    let items: [[String: Data]]

    var size: Int { items.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } } }
    var fileURLs: [URL] {
        items.compactMap {
            guard let data = $0[NSPasteboard.PasteboardType.fileURL.rawValue],
                  let url = URL(dataRepresentation: data, relativeTo: nil), url.isFileURL else { return nil }
            return url
        }
    }
    var photo: (type: UTType, data: Data)? {
        guard let item = items.first else { return nil }
        for identifier in [UTType.png, .jpeg, .heic, .gif, .tiff, .webP].map(\.identifier) + item.keys.sorted() {
            guard let bytes = item[identifier], let type = UTType(identifier), type.conforms(to: .image) else { continue }
            return (type, bytes)
        }
        return nil
    }
    private var textData: Data? {
        items.first?[NSPasteboard.PasteboardType.string.rawValue] ?? items.first?[NSPasteboard.PasteboardType.URL.rawValue]
    }
    var text: String? { textData.flatMap { String(data: $0, encoding: .utf8) } }
    var textPreview: String? { textData.map { String(decoding: $0.prefix(64 * 1024), as: UTF8.self) } }
    var title: String {
        let files = fileURLs
        if let file = files.first {
            return file.lastPathComponent + (files.count > 1 ? " +\(files.count - 1)" : "")
        }
        if photo != nil { return "Изображение" }
        return textPreview?.prefix(150).split(maxSplits: 1, whereSeparator: \.isNewline).first.map(String.init)
            ?? "Форматированный текст"
    }
    var icon: String { !fileURLs.isEmpty ? "doc" : photo == nil ? "text.alignleft" : "photo" }
    var canAsk: Bool { textData != nil || photo != nil || fileURLs.contains(where: QuickChatImage.supports) }
    var canShelve: Bool { !fileURLs.isEmpty || photo != nil }

    func write(to pasteboard: NSPasteboard) -> Bool {
        let objects = items.map { formats -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in formats { item.setData(data, forType: .init(type)) }
            return item
        }
        guard !objects.isEmpty else { return false }
        pasteboard.clearContents()
        return pasteboard.writeObjects(objects)
    }
}

final class ClipboardPocket: ObservableObject {
    private static let archive = "clipboard-pocket.plist"
    private static let itemLimit = 24 * 1024 * 1024
    private static let totalLimit = 128 * 1024 * 1024
    private static let hiddenTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
    @Published private(set) var entries: [PocketEntry] = []
    @Published private(set) var selectedIndex: Int? = 0
    @Published var search = "" { didSet { selectedIndex = 0 } }
    private let pasteboard = NSPasteboard.general
    private let storage = DispatchQueue(label: "local.kirill.chubzik.clipboard-pocket")
    private var timer: Timer?
    private var lastChange = -1
    private var window: NSWindow?
    private var showsHistory = false
    private var keyMonitor: Any?
    private var origin: pid_t?
    private weak var originWindow: NSWindow?
    private var originField: AXUIElement?
    private var pasteGeneration = UUID()
    private var loading = false
    private var loadGeneration = UUID()
    private var save: DispatchWorkItem?
    var onAsk: ((PocketEntry) -> Void)?
    var onShelf: ((PocketEntry) -> Void)?

    var displayed: [PocketEntry] {
        if !showsHistory { return Array(entries.prefix(8)) }
        if search.isEmpty { return entries }
        return entries.filter { $0.title.localizedStandardContains(search) || $0.textPreview?.localizedStandardContains(search) == true }
    }

    var selection: PocketEntry? {
        let options = displayed
        guard let selectedIndex, options.indices.contains(selectedIndex) else { return nil }
        return options[selectedIndex]
    }

    func setEnabled(_ enabled: Bool) {
        if enabled {
            guard timer == nil else { return }
            loading = true
            let generation = UUID()
            loadGeneration = generation
            storage.async { [weak self] in
                let url = LocalSettings.directory.appendingPathComponent(Self.archive)
                let data = try? Data(contentsOf: url)
                let saved = data.flatMap { bytes in
                    bytes.count < Self.totalLimit + 2 * 1024 * 1024
                        ? try? PropertyListDecoder().decode([PocketEntry].self, from: bytes) : nil
                } ?? []
                DispatchQueue.main.async { [weak self] in
                    guard let self, self.loadGeneration == generation else { return }
                    self.replaceEntries(self.entries + saved.filter { old in !self.entries.contains { $0.items == old.items } })
                    self.loading = false
                    self.prune()
                    if self.save != nil { self.saveSoon() }
                }
            }
            lastChange = pasteboard.changeCount
            timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in self?.collect() }
            timer?.tolerance = 0.15
        } else {
            let wasEnabled = timer != nil
            timer?.invalidate()
            timer = nil
            loading = false
            loadGeneration = UUID()
            close()
            entries = []
            save?.cancel()
            save = nil
            if wasEnabled {
                storage.async {
                    try? FileManager.default.removeItem(at: LocalSettings.directory.appendingPathComponent(Self.archive))
                }
            }
        }
    }

    private func collect() {
        prune()
        let count = pasteboard.changeCount
        guard lastChange != count else { return }
        lastChange = count
        if let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier?.lowercased(),
           ["1password", "bitwarden", "keepass", "passwords", "keychainaccess", "lastpass"].contains(where: app.contains) {
            return
        }
        guard let sources = pasteboard.pasteboardItems, (1...20).contains(sources.count),
              sources.allSatisfy({ Self.hiddenTypes.isDisjoint(with: $0.types.map(\.rawValue)) }) else { return }
        var size = 0
        var values: [[String: Data]] = []
        for item in sources {
            var formats: [String: Data] = [:]
            for type in item.types where Self.supports(type) {
                guard let data = item.data(forType: type), !data.isEmpty else { continue }
                size += data.count
                guard size <= Self.itemLimit else { return }
                formats[type.rawValue] = data
            }
            guard !formats.isEmpty else { return }
            values.append(formats)
        }
        guard pasteboard.changeCount == count else { return }
        let entry = PocketEntry(id: UUID(), copied: .now, items: values)
        replaceEntries([entry] + entries.filter { $0.items != values })
        prune()
        saveSoon()
    }

    private static func supports(_ type: NSPasteboard.PasteboardType) -> Bool {
        if [NSPasteboard.PasteboardType.string, .URL, .fileURL, .html, .rtf, .rtfd].contains(type) { return true }
        return UTType(type.rawValue)?.conforms(to: .image) == true
    }

    private func replaceEntries(_ updated: [PocketEntry]) {
        let selected = window == nil ? nil : selection
        entries = updated
        if let selected { selectedIndex = displayed.firstIndex { $0.id == selected.id || $0.items == selected.items } }
    }

    private func prune(now: Date = .now) {
        var total = 0
        let cutoff = now.addingTimeInterval(-24 * 3600)
        let retained = entries.lazy.filter { $0.copied > cutoff }.prefix(180).prefix { entry in
            total += entry.size
            return total <= Self.totalLimit
        }
        if retained.count != entries.count {
            replaceEntries(Array(retained))
            saveSoon()
        }
    }

    private func saveSoon() {
        save?.cancel()
        let item = DispatchWorkItem { [weak self] in self?.flush() }
        save = item
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5, execute: item)
    }

    func flush(wait: Bool = false) {
        guard timer != nil else {
            if wait { storage.sync {} }
            return
        }
        if wait { collect() }
        guard !loading else { return }
        save?.cancel()
        save = nil
        let snapshot = entries
        storage.async {
            let encoder = PropertyListEncoder()
            encoder.outputFormat = .binary
            do {
                let directory = LocalSettings.directory
                try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true,
                                                        attributes: [.posixPermissions: 0o700])
                let file = directory.appendingPathComponent(Self.archive)
                try encoder.encode(snapshot).write(to: file, options: .atomic)
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
            } catch { NSLog("Чубзик: не удалось сохранить историю буфера") }
        }
        if wait { storage.sync {} }
    }

    func show(at point: CGPoint) {
        if window?.isVisible == true { close(); return }
        pasteGeneration = UUID()
        origin = NSWorkspace.shared.frontmostApplication?.processIdentifier
        originWindow = NSApp.keyWindow
        originField = originWindow == nil ? origin.flatMap(Self.focusedField) : nil
        collect()
        present(at: point, full: false)
    }

    func close() {
        pasteGeneration = UUID()
        if let keyMonitor { NSEvent.removeMonitor(keyMonitor) }
        keyMonitor = nil
        window?.orderOut(nil)
        window = nil
    }

    func closeIfOutside(_ point: CGPoint) {
        if let window, !window.frame.contains(point) { close() }
    }

    func applicationActivated(_ application: NSRunningApplication) {
        guard let origin, application.processIdentifier != origin, application.processIdentifier != getpid() else { return }
        close()
        self.origin = nil
        originWindow = nil
        originField = nil
    }

    private func present(at point: CGPoint, full: Bool) {
        guard let screen = NSScreen.screens.first(where: { $0.frame.contains(point) }) ?? NSScreen.main else { return }
        close()
        showsHistory = full
        search = ""
        let area = screen.visibleFrame.insetBy(dx: 10, dy: 10)
        let size = CGSize(width: min(area.width, full ? 550 : 330),
                          height: min(area.height, full ? 450 : max(125, CGFloat(min(entries.count, 8) * 39 + 87))))
        let x = full ? area.midX - size.width / 2 : min(area.maxX - size.width, max(area.minX, point.x + 12))
        let y = full ? area.midY - size.height / 2 : min(area.maxY - size.height, max(area.minY, point.y - size.height - 12))
        let panel = OverlayPanel(frame: CGRect(origin: CGPoint(x: x, y: y), size: size), keyboard: true)
        panel.title = full ? "История буфера Чубзика" : "Карманы буфера Чубзика"
        panel.appearance = NSAppearance(named: .darkAqua)
        panel.level = NSWindow.Level(rawValue: NSWindow.Level.mainMenu.rawValue + 5)
        panel.becomesKeyOnlyIfNeeded = false
        panel.hasShadow = true
        let content = NSHostingView(rootView: ClipboardPocketView(pocket: self, full: full,
            showAll: { [weak self] in self?.present(at: point, full: true) }))
        content.sizingOptions = []
        panel.contentView = content
        window = panel
        keyMonitor = NSEvent.addLocalMonitorForEvents(matching: [.keyDown]) { [weak self, weak panel] event in
            guard let self, let panel, event.window === panel || panel.isKeyWindow,
                  event.modifierFlags.intersection([.command, .option, .control, .shift]).isEmpty,
                  (panel.firstResponder as? NSTextView)?.hasMarkedText() != true else { return event }
            switch event.keyCode {
            case 53: self.close()
            case 125, 126:
                let count = self.displayed.count
                if count > 0 {
                    let delta = event.keyCode == 125 ? 1 : -1
                    self.selectedIndex = self.selectedIndex.map { min(count - 1, max(0, $0 + delta)) }
                        ?? (delta > 0 ? 0 : count - 1)
                }
            case 36, 76:
                if let selection = self.selection { self.use(selection, action: .paste) }
            default: return event
            }
            return nil
        }
        panel.orderFrontRegardless()
        panel.makeKeyAndOrderFront(nil)
    }

    func use(_ entry: PocketEntry, action: PocketAction) {
        close()
        switch action {
        case .ask: onAsk?(entry)
        case .shelf: onShelf?(entry)
        case .paste:
            if let originWindow, originWindow.isVisible {
                originWindow.makeKeyAndOrderFront(nil)
                if entry.write(to: pasteboard) {
                    lastChange = pasteboard.changeCount
                    NSApp.sendAction(#selector(NSText.paste(_:)), to: nil, from: nil)
                }
                return
            }
            guard let origin, origin != getpid(), CGPreflightPostEventAccess(),
                  let app = NSRunningApplication(processIdentifier: origin), !app.isTerminated else { return }
            let destination = NSWorkspace.shared.frontmostApplication?.processIdentifier
            if destination == getpid() { app.activate() }
            let generation = UUID()
            pasteGeneration = generation
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) { [weak self] in
                guard let self, self.pasteGeneration == generation,
                      NSWorkspace.shared.frontmostApplication?.processIdentifier == origin else { return }
                if let field = self.originField {
                    guard let current = Self.focusedField(origin), CFEqual(field, current) else { return }
                }
                guard entry.write(to: self.pasteboard) else { return }
                self.lastChange = self.pasteboard.changeCount
                for pressed in [true, false] {
                    let event = CGEvent(keyboardEventSource: nil, virtualKey: 9, keyDown: pressed)
                    event?.flags = pressed ? .maskCommand : []
                    event?.postToPid(origin)
                }
            }
        }
    }

    private static func focusedField(_ pid: pid_t) -> AXUIElement? {
        guard AXIsProcessTrusted() else { return nil }
        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, 0.10)
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute as CFString, &value) == .success,
              let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        return (value as! AXUIElement)
    }
}

enum PocketAction { case paste, shelf, ask }

private struct ClipboardPocketView: View {
    @ObservedObject var pocket: ClipboardPocket
    let full: Bool
    let showAll: () -> Void
    @FocusState private var focus: Bool

    var body: some View {
        VStack(alignment: .leading, spacing: 8) {
            if full {
                TextField("Найти в истории буфера", text: $pocket.search)
                    .textFieldStyle(.roundedBorder).focused($focus)
            }
            if pocket.displayed.isEmpty {
                Text(pocket.search.isEmpty ? "Ничего не скопировано" : "Совпадений нет")
                    .foregroundStyle(OrbitStyle.muted)
                    .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 2) {
                            ForEach(Array(pocket.displayed.enumerated()), id: \.element.id) { index, entry in
                                Button { pocket.use(entry, action: .paste) } label: {
                                    HStack(spacing: 8) {
                                        if let photo = entry.photo, let image = NSImage(data: photo.data) {
                                            Image(nsImage: image).resizable().scaledToFit().frame(width: 28, height: 24)
                                        } else {
                                            Image(systemName: entry.icon).frame(width: 28)
                                        }
                                        Text(entry.title).lineLimit(1)
                                        Spacer(minLength: 0)
                                    }
                                    .padding(.horizontal, 6)
                                    .frame(height: 37)
                                    .background(.white.opacity(pocket.selectedIndex == index ? 0.12 : 0), in: RoundedRectangle(cornerRadius: 8))
                                    .contentShape(Rectangle())
                                }
                                .buttonStyle(.plain)
                                .id(entry.id)
                                .accessibilityAddTraits(pocket.selectedIndex == index ? .isSelected : [])
                            }
                        }
                    }
                    .onChange(of: pocket.selection?.id) { _, id in
                        if let id { proxy.scrollTo(id) }
                    }
                }
            }
            HStack {
                if !full { Button("Вся история", action: showAll).disabled(pocket.entries.isEmpty) }
                Spacer(minLength: 2)
                if let selection = pocket.selection, selection.canShelve {
                    Button("На полку") { pocket.use(selection, action: .shelf) }
                }
                if let selection = pocket.selection, selection.canAsk {
                    Button("Спросить") { pocket.use(selection, action: .ask) }
                }
            }
            .buttonStyle(.borderless)
        }
        .font(.system(size: 12))
        .foregroundStyle(OrbitStyle.text)
        .padding(12)
        .background { OrbitStyle.glass(radius: 14) }
        .clipShape(RoundedRectangle(cornerRadius: 14))
        .onAppear { if full { focus = true } }
    }
}
